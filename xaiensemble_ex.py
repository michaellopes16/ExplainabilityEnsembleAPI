  def perform_sensitivity_analysis(self, X_train, X_test_original_instance, model, class_names, npermutations, last_layer_name, num_perturbations=5, noise_strength=0.01):
        print("\n" + "="*50)
        print("=== INITIATING SENSITIVITY ANALYSIS ===")
        print("="*50 + "\n")
        
        metrics = self.metrics
        
        # 1. Explicação da instância original
        print("\n--- Explaining Original Instance ---")
        _, _, _, df_ensemble_orig, _ = \
            self.run_all_methods_once(X_train, X_test_original_instance, model, class_names, npermutations, last_layer_name)
        
        # Verificar se df_ensemble_orig está vazio
        if df_ensemble_orig.empty:
            print("Original ensemble explanation is empty. Skipping sensitivity analysis.")
            return

        original_ensemble_features = set(df_ensemble_orig['Column'])
        
        # Salvar a explicação original para referência
        self.api.save_dataframe_to_csv(df_ensemble_orig, "sensitivity_original_ensemble.csv")

        jaccard_scores = []
        overlap_scores = []
        kendall_scores = []

        for i in range(num_perturbations):
            print(f"\n--- Perturbation {i+1}/{num_perturbations} ---")
            # Adicionar ruído gaussiano à instância
            perturbed_instance = X_test_original_instance + np.random.normal(0, noise_strength, X_test_original_instance.shape)
            
            # Garanta que os valores perturbados ainda estejam dentro de um intervalo razoável (se aplicável)
            # Ex: perturbed_instance = np.clip(perturbed_instance, 0, 1) se os dados forem normalizados entre 0 e 1
            # Se seus dados são de sensor, valores negativos podem ser problemáticos.
            perturbed_instance = np.maximum(0, perturbed_instance) # Garante que não há valores negativos

            _, _, _, df_ensemble_pert, _ = \
                self.run_all_methods_once(X_train, perturbed_instance, model, class_names, npermutations, last_layer_name)
            
            if df_ensemble_pert.empty:
                print(f"Perturbation {i+1}: Ensemble result is empty, skipping metrics for this perturbation.")
                continue

            perturbed_ensemble_features = set(df_ensemble_pert['Column'])
            
            # Salvar cada explicação perturbada
            self.api.save_dataframe_to_csv(df_ensemble_pert, f"sensitivity_perturbed_ensemble_{i+1}.csv")

            # Jaccard Index
            jaccard = metrics.calculate_jaccard_index(original_ensemble_features, perturbed_ensemble_features)
            jaccard_scores.append(jaccard)

            # Overlap Coefficient
            overlap = metrics.calculate_overlap_coefficient(original_ensemble_features, perturbed_ensemble_features)
            overlap_scores.append(overlap)

            # Kendall's Tau (ranking correlation)
            kendall = metrics.calculate_ranking_correlation(df_ensemble_orig, df_ensemble_pert, method='kendall')
            kendall_scores.append(kendall)
            
            print(f"Perturbation {i+1}: Jaccard={jaccard:.3f}, Overlap={overlap:.3f}, Kendall's Tau={kendall:.3f}")

        # Salvar métricas agregadas de sensibilidade
        if jaccard_scores: # Verifica se a lista não está vazia antes de calcular a média
            sensitivity_summary_data = {
                'Metric': ['Average Jaccard Index', 'Average Overlap Coefficient', 'Average Kendall\'s Tau'],
                'Value': [np.mean(jaccard_scores), np.mean(overlap_scores), np.mean(kendall_scores)]
            }
            df_sensitivity_summary = pd.DataFrame(sensitivity_summary_data)
            self.api.save_dataframe_to_csv(df_sensitivity_summary, "sensitivity_metrics_summary.csv")

            print(f"\nAverage Jaccard Index: {np.mean(jaccard_scores):.3f}")
            print(f"Average Overlap Coefficient: {np.mean(overlap_scores):.3f}")
            print(f"Average Kendall's Tau: {np.mean(kendall_scores):.3f}")
        else:
            print("\nNo valid perturbed explanations generated for calculating average metrics.")


        print("\n" + "="*50)
        print("=== SENSITIVITY ANALYSIS COMPLETED ===")
        print("="*50 + "\n")


