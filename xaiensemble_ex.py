import numpy as np
from scipy.stats import kendalltau

class Metrics:
    @staticmethod
    def calculate_jaccard_index(set1, set2):
        """Índice de Jaccard entre dois conjuntos."""
        if not set1 or not set2:
            return 0.0
        intersection = len(set1.intersection(set2))
        union = len(set1.union(set2))
        return intersection / union

    @staticmethod
    def calculate_overlap_coefficient(set1, set2):
        """Coeficiente de sobreposição entre dois conjuntos."""
        if not set1 or not set2:
            return 0.0
        intersection = len(set1.intersection(set2))
        min_size = min(len(set1), len(set2))
        return intersection / min_size

    @staticmethod
    def calculate_ranking_correlation(df1, df2, method='kendall'):
        """
        Correlação entre rankings de dois DataFrames com colunas: 'Column' e 'Mean'.
        Retorna correlação de Kendall por padrão.
        """
        try:
            # 1. Interseção de colunas comuns
            common_features = sorted(set(df1['Column']).intersection(set(df2['Column'])))
            if not common_features:
                return 0.0

            # 2. Filtragem e alinhamento
            df1_filtered = df1[df1['Column'].isin(common_features)].drop_duplicates(subset='Column').set_index('Column')
            df2_filtered = df2[df2['Column'].isin(common_features)].drop_duplicates(subset='Column').set_index('Column')

            df1_filtered = df1_filtered.loc[common_features]
            df2_filtered = df2_filtered.loc[common_features]

            # 3. Extração dos valores
            scores1 = df1_filtered['Mean'].values
            scores2 = df2_filtered['Mean'].values

            if scores1.shape != scores2.shape:
                raise ValueError(f"Shapes incompatíveis: scores1 {scores1.shape}, scores2 {scores2.shape}")

            # 4. Correlação
            if method == 'kendall':
                tau, _ = kendalltau(scores1, scores2)
                return tau if not np.isnan(tau) else 0.0
            else:
                raise ValueError(f"Método de correlação não suportado: {method}")
        except Exception as e:
            print(f"Erro ao calcular correlação de ranking: {e}")
            return 0.0

